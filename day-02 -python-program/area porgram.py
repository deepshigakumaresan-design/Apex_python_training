import math

# Integer values
radius = 5
length = 10
width = 4
side = 6

# Area calculations
circle_area = math.pi * radius * radius
rectangle_area = length * width
square_area = side * side

# Output
print("Radius =", radius)
print("Area of Circle =", circle_area)

print("Length =", length)
print("Width =", width)
print("Area of Rectangle =", rectangle_area)

print("Side =", side)
print("Area of Square =", square_area)
